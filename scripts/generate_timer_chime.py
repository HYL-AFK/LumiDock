#!/usr/bin/env python3
"""Generate the LumiDock timer chime placeholder PCM (16 kHz mono s16le).

Synthesizes a three-note "ding-dong-ding" chime (~1.2 s) and emits it as a C
source file consumed by the timer service.  Replace the generated arrays with
a real ringtone converted by convert_startup_audio.ps1 whenever desired.
"""

import math
import os

SAMPLE_RATE = 16000
OUT_C = os.path.join(os.path.dirname(__file__), "..", "main", "MID", "system", "timer_chime_audio.c")
OUT_H = os.path.join(os.path.dirname(__file__), "..", "main", "MID", "system", "timer_chime_audio.h")

NOTES = [
    (880.0, 0.00, 0.38),  # A5
    (659.25, 0.38, 0.38),  # E5
    (880.0, 0.76, 0.44),  # A5
]
TOTAL_SECONDS = 1.2


def envelope(t, start, length):
    if t < start or t >= start + length:
        return 0.0
    local = (t - start) / length
    attack = min(1.0, local / 0.05)
    decay = math.exp(-3.5 * local)
    return attack * decay


def main():
    total = int(SAMPLE_RATE * TOTAL_SECONDS)
    samples = []
    for index in range(total):
        t = index / SAMPLE_RATE
        value = 0.0
        for freq, start, length in NOTES:
            value += math.sin(2.0 * math.pi * freq * t) * envelope(t, start, length)
        value = max(-1.0, min(1.0, value * 0.55))
        samples.append(int(round(value * 32767.0)))

    values = []
    for i in range(0, len(samples), 12):
        row = ", ".join(str(s) for s in samples[i:i + 12])
        values.append("    " + row)
    body = ",\n".join(values)

    with open(OUT_H, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(
            "/* Timer chime placeholder PCM, generated by scripts/generate_timer_chime.py.\n"
            " * 16 kHz mono s16le, ~1.2 s three-note chime.  Replace with a real\n"
            " * ringtone converted through scripts/convert_startup_audio.ps1. */\n"
            "#pragma once\n"
            "#include <stddef.h>\n"
            "#include <stdint.h>\n"
            "\n"
            "#define TIMER_CHIME_PCM_SAMPLES %uU\n"
            "\n"
            "extern const int16_t timer_chime_pcm[TIMER_CHIME_PCM_SAMPLES];\n"
            % len(samples)
        )

    with open(OUT_C, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(
            '/* Timer chime placeholder PCM, generated by scripts/generate_timer_chime.py. */\n'
            '#include "timer_chime_audio.h"\n'
            "\n"
            "const int16_t timer_chime_pcm[TIMER_CHIME_PCM_SAMPLES] = {\n"
            + body
            + ",\n};\n"
        )

    print("wrote %s (%u samples, %.2f s)" % (OUT_C, len(samples), TOTAL_SECONDS))


if __name__ == "__main__":
    main()
